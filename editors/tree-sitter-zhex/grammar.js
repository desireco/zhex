// This editor grammar recognizes statements by line. The interpreter validates block indentation.
module.exports = grammar({
  name: 'zhex',
  extras: $ => [/[ \t\r]/, $.comment],
  word: $ => $.identifier,
  rules: {
    source_file: $ => seq(repeat(seq(optional($._statement), $._newline)), optional($._statement)),
    _newline: _ => '\n',
    _statement: $ => choice(
      $.word_definition, $.record_definition, $.choice_definition, $.alias_definition, $.variant_definition, $.field_definition, $.use_statement, $.binding, $.indexed_assignment, $.assignment, $.if_header, $.elif_header,
      $.else_header, $.for_header, $.flow_header, $.case_header, $.return_statement, $.expression_statement,
    ),
    word_definition: $ => seq('word', field('name', $.identifier), '(', optional(seq($.parameter, repeat(seq(',', $.parameter)))), ')', '->', field('result', choice($.type, $.result_type))),
    record_definition: $ => seq('type', field('name', $.identifier), '=', 'record'),
    alias_definition: $ => seq('type', field('name', $.identifier), '=', 'alias', field('target', $.type)),
    choice_definition: $ => seq('type', field('name', $.identifier), optional(seq('<', $.identifier, '>')), '=', 'choice'),
    variant_definition: $ => seq(field('name', $.identifier), '(', $.parameter, repeat(seq(',', $.parameter)), ')'),
    field_definition: $ => seq(field('name', $.identifier), ':', field('type', $.type)),
    use_statement: $ => seq('use', field('name', $.identifier)),
    parameter: $ => seq(field('name', $.identifier), ':', field('type', $.type)),
    type: $ => choice('Int', 'Bool', 'String', 'Unit', 'Buffer', 'File', 'Error', $.identifier, seq(choice('List', 'Array', 'Map', 'Option', $.identifier), '<', $.type, repeat(seq(',', $.type)), '>')),
    error_type: _ => choice('InputError', 'ParseError', 'FileError', 'BufferError', 'Error'),
    result_type: $ => seq('Result', '<', $.type, ',', $.error_type, '>'),
    binding: $ => seq(choice('let', 'var'), field('name', $.identifier), optional(seq(':', $.type)), '=', field('value', $._expression)),
    indexed_assignment: $ => seq($.index_expression, '=', $._expression),
    assignment: $ => seq(field('name', $.identifier), '=', field('value', $._expression)),
    if_header: $ => seq('if', $._expression),
    elif_header: $ => seq('elif', $._expression),
    else_header: _ => 'else',
    for_header: $ => seq('for', field('name', $.identifier), optional(seq(',', field('value', $.identifier))), 'in', choice(
      seq('range', '(', $._expression, ',', $._expression, ')'),
      seq('file.lines', '(', $._expression, ')'),
      $._expression,
    )),
    case_header: $ => seq('case', choice($.identifier, $.call_expression)),
    match_expression: $ => prec.right(-1, seq('match', $._expression)),
    flow_header: $ => seq('flow', $._expression),
    return_statement: $ => seq('return', $._expression),
    expression_statement: $ => $._expression,
    _expression: $ => choice($.match_expression, $.identifier, $.map_literal, $.list_literal, $.index_expression, $.index_assignment, $.integer, $.boolean, $.string, $.parenthesized_expression, $.call_expression, $.binary_expression, $.unary_expression, $.try_expression, $.catch_expression),
    map_literal: $ => seq('{', optional(seq($._expression, ':', $._expression, repeat(seq(',', $._expression, ':', $._expression)))), '}'),
    list_literal: $ => seq('[', optional(seq($._expression, repeat(seq(',', $._expression)))), ']'),
    index_expression: $ => prec.left(9, seq($._expression, '[', optional(seq($._expression, repeat(seq(',', $._expression)))), ']')),
    index_assignment: $ => seq('(', $.index_expression, '=', $._expression, ')'),
    parenthesized_expression: $ => seq('(', $._expression, ')'),
    call_expression: $ => prec(9, seq(field('function', $.identifier), '(', optional(seq($._expression, repeat(seq(',', $._expression)))), ')')),
    catch_expression: $ => prec.left(0, seq($._expression, 'catch', optional($.identifier))),
    try_expression: $ => prec.left(8, seq($._expression, 'try')),
    unary_expression: $ => prec(7, seq(choice('-', 'not'), $._expression)),
    binary_expression: $ => choice(...[
      [1, ['or']], [2, ['and']], [3, ['==', '!=']], [4, ['<', '<=', '>', '>=']],
      [5, ['+', '-']], [6, ['*', '/', '%']],
    ].map(([precedence, operators]) => prec.left(precedence, seq($._expression, field('operator', operators.length === 1 ? operators[0] : choice(...operators)), $._expression)))),
    identifier: _ => /[A-Za-z_][A-Za-z0-9_]*([-\.][A-Za-z_][A-Za-z0-9_]*)*/,
    integer: _ => /[0-9]+/,
    boolean: _ => choice('true', 'false'),
    string: $ => seq('"', repeat(choice($.escape_sequence, token.immediate(prec(1, /[^"\\\n\r]+/)))), '"'),
    escape_sequence: _ => token.immediate(/\\([abfnrtv\\"]|[0-7]{3}|x[0-9A-Fa-f]{2}|u[0-9A-Fa-f]{4}|U[0-9A-Fa-f]{8})/),
    comment: _ => /#[^\n]*/,
  },
});
