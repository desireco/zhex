package lang

import (
	"bytes"
	"os"
	"testing"
)

func TestLifeBlockBlinkerAndGliderOracles(t *testing.T) {
	source, err := os.ReadFile("../../examples/life.zhex")
	if err != nil {
		t.Fatal(err)
	}
	oracles := `
let block: Array<Int> = array.new([7, 7], 0) try
block[2, 2] = 1
block[2, 3] = 1
block[3, 2] = 1
block[3, 3] = 1
let block-next = advance(block) try
print("BLOCK")
show(block-next) try

let blinker: Array<Int> = array.new([7, 7], 0) try
blinker[3, 2] = 1
blinker[3, 3] = 1
blinker[3, 4] = 1
let blinker-vertical = advance(blinker) try
let blinker-horizontal = advance(blinker-vertical) try
print("BLINKER 1")
show(blinker-vertical) try
print("BLINKER 2")
show(blinker-horizontal) try

let edge: Array<Int> = array.new([7, 7], 0) try
edge[3, 0] = 1
edge[3, 1] = 1
edge[3, 2] = 1
let edge-next = advance(edge) try
print("EDGE")
show(edge-next) try
`
	var output bytes.Buffer
	if err := Run("life-oracle.zhex", string(source)+oracles, bytes.NewBuffer(nil), &output); err != nil {
		t.Fatal(err)
	}
	const want = `Generation 0
.......
.......
...#...
....#..
..###..
.......
.......
Generation 1
.......
.......
.......
..#.#..
...##..
...#...
.......
Generation 2
.......
.......
.......
....#..
..#.#..
...##..
.......
Generation 3
.......
.......
.......
...#...
....##.
...##..
.......
Generation 4
.......
.......
.......
....#..
.....#.
...###.
.......
BLOCK
.......
.......
..##...
..##...
.......
.......
.......
BLINKER 1
.......
.......
...#...
...#...
...#...
.......
.......
BLINKER 2
.......
.......
.......
..###..
.......
.......
.......
EDGE
.......
.......
.#.....
.#.....
.#.....
.......
.......
`
	if output.String() != want {
		t.Fatalf("Life patterns differ from their oracles:\n got:\n%s\nwant:\n%s", output.String(), want)
	}
}
